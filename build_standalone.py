#!/usr/bin/env python3
"""Build a single-file, offline HTML edition of Morandi Archive Studio.

Usage:
    python build_standalone.py [output.html]

All CSS, JavaScript, icon assets and Font Awesome webfonts are inlined, so the
result can be opened directly from the desktop (file://) without a web server.
"""

from __future__ import annotations

import base64
import io
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
DEFAULT_OUTPUT = ROOT / "dist" / "Morandi-Archive-Studio.html"


def data_uri(data: bytes, mime: str) -> str:
    return f"data:{mime};base64,{base64.b64encode(data).decode('ascii')}"


def inline_fontawesome_css() -> str:
    css_path = ROOT / "lib" / "fontawesome" / "css" / "all.min.css"
    css = css_path.read_text(encoding="utf-8")

    def replace_url(match: re.Match[str]) -> str:
        raw = match.group(1).strip().strip("\"'")
        if "webfonts/" not in raw:
            return match.group(0)
        font_path = (css_path.parent / raw).resolve()
        if not font_path.is_file():
            return match.group(0)
        return f"url({data_uri(font_path.read_bytes(), 'font/woff2')})"

    return re.sub(r"url\(([^)]+)\)", replace_url, css)


def inline_icon() -> str:
    image = Image.open(ROOT / "icon.png").convert("RGBA")
    image.thumbnail((256, 256), Image.Resampling.LANCZOS)
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return data_uri(buffer.getvalue(), "image/png")


def build(output: Path) -> Path:
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    styles = (ROOT / "styles.css").read_text(encoding="utf-8")
    app_js = (ROOT / "app.js").read_text(encoding="utf-8")
    jszip_js = (ROOT / "lib" / "jszip.min.js").read_text(encoding="utf-8")
    fa_css = inline_fontawesome_css()
    icon_uri = inline_icon()

    # Keep inline script/style blocks safe if source contains closing tags.
    app_js = app_js.replace("</script", "<\\/script")
    jszip_js = jszip_js.replace("</script", "<\\/script")
    styles = styles.replace("</style", "<\\/style")
    fa_css = fa_css.replace("</style", "<\\/style")

    html = html.replace(
        '<link rel="manifest" href="manifest.webmanifest">',
        "<!-- Standalone build: web manifest intentionally omitted. -->",
    )
    html = html.replace(
        "  <!-- Local Icons (no network dependency) -->\n"
        '  <link rel="stylesheet" href="lib/fontawesome/css/all.min.css">',
        "  <!-- Inlined local icons, styles and scripts (fully offline) -->\n"
        f"  <style>\n{fa_css}\n  </style>",
    )
    html = html.replace(
        '  <link rel="stylesheet" href="styles.css">',
        f"  <style>\n{styles}\n  </style>",
    )
    html = html.replace(
        '  <script src="lib/jszip.min.js"></script>',
        f"  <script>\n{jszip_js}\n  </script>",
    )
    html = html.replace(
        '  <script src="app.js"></script>',
        f"  <script>\n{app_js}\n  </script>",
    )
    html = html.replace('href="icon.png"', f'href="{icon_uri}"')
    html = html.replace('src="icon.png"', f'src="{icon_uri}"')

    banner = (
        "<!--\n"
        "  Morandi Archive Studio — single-file offline build\n"
        "  Generated by build_standalone.py. No external network requests.\n"
        "-->\n"
    )
    html = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + banner, 1)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(html, encoding="utf-8")

    leftovers = re.findall(r'(?:src|href)="(?!data:|#)([^"]+)"', html)
    leftovers = [item for item in leftovers if not item.startswith(("http://", "https://"))]
    print(f"Wrote: {output}")
    print(f"Size:  {output.stat().st_size / (1024 * 1024):.2f} MB")
    print(f"Local references left: {leftovers or 'none'}")
    return output


if __name__ == "__main__":
    target = Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else DEFAULT_OUTPUT
    build(target.resolve())
